import { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { ChevronDown } from "lucide-react";
import { getMyReports } from "../../services/reportService";
import { SkeletonTable } from "../../components/Skeleton";

function Reports() {
  const [reports, setReports] = useState([]);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(true);
  const [expandedId, setExpandedId] = useState(null);

  useEffect(() => {
    const fetchReports = async () => {
      try {
        const res = await getMyReports();
        setReports(res.data.reports);
      } catch (err) {
        setError(err.response?.data?.message || "Unable to load reports.");
      } finally {
        setLoading(false);
      }
    };

    fetchReports();
  }, []);

  const toggleExpand = (id) => {
    setExpandedId(expandedId === id ? null : id);
  };

  if (loading) {
    return (
      <div>
        <h1 className="page-heading">My Reports</h1>
        <p className="page-subheading">
          Reports generated by a doctor after reviewing your scans.
        </p>
        <div className="mt-6 overflow-x-auto">
          <SkeletonTable columns={5} rows={4} />
        </div>
      </div>
    );
  }

  return (
    <div>
      <h1 className="page-heading">My Reports</h1>
      <p className="page-subheading">
        Reports generated by a doctor after reviewing your scans.
      </p>

      {error && <p className="mt-4 text-sm text-danger-600">{error}</p>}

      <div className="mt-6 overflow-x-auto">
        <table className="table-base">
          <thead>
            <tr>
              <th>Report ID</th>
              <th>Scan</th>
              <th>Doctor</th>
              <th>Date</th>
              <th>Action</th>
            </tr>
          </thead>
          <tbody>
            {reports.length === 0 ? (
              <tr>
                <td colSpan="5" className="text-center text-neutral-400">
                  No reports yet. A doctor will generate one after reviewing your scan.
                </td>
              </tr>
            ) : (
              reports.map((report) => (
                <>
                  <tr key={report._id}>
                    <td>{report.reportId}</td>
                    <td>{report.scanId?.scanId || "—"}</td>
                    <td>{report.doctorId?.name || "—"}</td>
                    <td>{new Date(report.generatedAt).toLocaleDateString()}</td>
                    <td className="flex items-center gap-3">
                      {report.scanId?._id && (
                        <Link
                          to={`/patient/analysis/${report.scanId._id}`}
                          className="font-medium text-primary-600 hover:text-primary-700"
                        >
                          View Scan
                        </Link>
                      )}
                      <button
                        onClick={() => toggleExpand(report._id)}
                        className="inline-flex items-center gap-1 font-medium text-neutral-600 hover:text-primary-600"
                      >
                        Details
                        <ChevronDown
                          className={`h-4 w-4 transition-transform ${
                            expandedId === report._id ? "rotate-180" : ""
                          }`}
                        />
                      </button>
                    </td>
                  </tr>
                  {expandedId === report._id && (
                    <tr key={`${report._id}-details`}>
                      <td colSpan="5" className="bg-neutral-50">
                        <div className="space-y-3 py-2">
                          <div>
                            <p className="text-xs font-semibold uppercase tracking-wide text-neutral-400">
                              Doctor's Notes
                            </p>
                            <p className="mt-1 text-sm text-neutral-700">
                              {report.doctorNotes || "No notes provided."}
                            </p>
                          </div>
                          <div>
                            <p className="text-xs font-semibold uppercase tracking-wide text-neutral-400">
                              Recommendation
                            </p>
                            <p className="mt-1 text-sm text-neutral-700">
                              {report.recommendation || "No recommendation provided."}
                            </p>
                          </div>
                        </div>
                      </td>
                    </tr>
                  )}
                </>
              ))
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
}

export default Reports;
